const CLASSIFIED = new Set([...CANDIDATES.map((candidate) => candidate.name), ...MODIFIERS, ...CARRIED, ...PRESERVED, ...Object.keys(EXCLUDED)]);

/**
 * Fails on names that aren’t candidates, as options to keep or skip
 * @param {string[]} names
 */
export function checkCandidates(names) {
  const known = CANDIDATES.map((candidate) => candidate.name);
  for (const name of names) {
    if (!known.includes(name)) throw new Error(`Unknown option: ${name} (options that can be kept or skipped: ${known.join(', ')})`);
  }
}

/**
 * Options without a place here
 * @param {string[]} options
 */
export const unclassified = (options) => options.filter((name) => !CLASSIFIED.has(name));

/**
 * The installed HTML Minifier’s version and options, by its schema, if readable
 * @returns {{version: string, options: string[]} | null}
 */
export function readSchema() {
  try {
    const filePackage = fileURLToPath(import.meta.resolve('html-minifier/package.json'));
    const { version } = JSON.parse(fs.readFileSync(filePackage, 'utf8'));
    const schema = JSON.parse(fs.readFileSync(path.join(path.dirname(filePackage), 'html-minifier.schema.json'), 'utf8'));
    return { version, options: Object.keys(schema.properties ?? {}) };
  } catch {
    return null;
  }
}

/**
 * Splits a starting configuration into what is carried into every run, candidate values to
 * evaluate (other than `true`), CLI settings to keep, and what is dropped
 * @param {Record<string, unknown>} config
 */
export function splitConfig(config) {
  /** @type {Record<string, unknown>} */
  const base = {};
  /** @type {Record<string, unknown>} */
  const values = {};
  /** @type {Record<string, unknown>} */
  const preserved = {};
  /** @type {string[]} */
  const ignored = [];
  const names = new Set(CANDIDATES.map((candidate) => candidate.name));
  // A preset can set how input is read, too (e.g., `caseSensitive`)
  const preset = typeof config.preset === 'string' ? /** @type {Record<string, Record<string, unknown>>} */ (PRESETS)[config.preset.toLowerCase()] : undefined;
  for (const name of CARRIED) {
    if (preset && name in preset) base[name] = preset[name];
  }
  for (const [name, value] of Object.entries(config)) {
    if (CARRIED.includes(name)) {
      base[name] = value;
    } else if (PRESERVED.includes(name)) {
      preserved[name] = value;
    } else if (names.has(name) && value !== false && value !== true) {
      values[name] = value;
    } else if (!names.has(name) || value === false) {
      ignored.push(name);
    }
  }
  return { base, values, preserved, ignored };
}